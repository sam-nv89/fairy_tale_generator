"""
Модуль экспорта сказок в различные форматы для электронных книг.

Поддерживаемые форматы:
  - TXT  — простой текст, универсальный
  - PDF  — для печати и чтения (fpdf2)
  - EPUB — стандарт электронных книг (ebooklib)
  - FB2  — FictionBook2, популярен в СНГ (xml.etree.ElementTree)
  - HTML — для чтения в браузере

Архитектура: каждый генератор — чистая функция, возвращающая bytes.
Это позволяет легко использовать их в st.download_button(data=...).
"""
import io
import re
import uuid
import zipfile
