import xml.etree.ElementTree as ET
from typing import Optional


# ---------------------------------------------------------------------------
# Вспомогательные утилиты
# ---------------------------------------------------------------------------

def _clean_text(text: str) -> str:
    """Удаляет markdown-разметку (**bold**, *italic*) из текста."""
    text = re.sub(r'\*\*(.*?)\*\*', r'\1', text)
    text = re.sub(r'\*(.*?)\*', r'\1', text)
    return text.strip()


def _paragraphs(body: str) -> list[str]:
    """Разбивает тело сказки на непустые абзацы."""
    return [p.strip() for p in body.split('\n') if p.strip()]


def _html_paragraphs(body: str) -> str:
    """Конвертирует тело сказки в HTML-абзацы с поддержкой **bold**."""
    result = []
    for para in _paragraphs(body):
        # Заменяем **text** → <strong>text</strong>
        para_html = re.sub(r'\*\*(.*?)\*\*', r'<strong>\1</strong>', para)
        result.append(f'<p>{para_html}</p>')
    return '\n'.join(result)


def _get_app_label(lang: str) -> str:
    """Возвращает подпись генератора на языке пользователя."""
    labels = {
        'ru': 'Сгенерировано Fairy Tale Generator',
        'en': 'Generated by Fairy Tale Generator',
        'es': 'Generado por Fairy Tale Generator',
        'fr': 'Généré par Fairy Tale Generator',
        'pt': 'Gerado pelo Fairy Tale Generator',
        'zh-CN': '由 Fairy Tale Generator 生成',
        'hi': 'Fairy Tale Generator द्वारा निर्मित',
        'de': 'Erstellt vom Fairy Tale Generator',
    }
    return labels.get(lang, labels['en'])


