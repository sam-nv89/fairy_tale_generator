# PDF (fpdf2)
# ---------------------------------------------------------------------------

def generate_pdf(title: str, body: str, lang: str = 'ru') -> bytes:
    """
    Генерирует PDF-файл с поддержкой Unicode/кириллицы через fpdf2.

    Стратегия поиска шрифта (Unicode TTF):
      1. DejaVuSans в папке fonts/ проекта — кроссплатформенный
      2. Arial на Windows (C:/Windows/Fonts/)
      3. DejaVuSans системный (Linux/Mac)
    Если шрифт не найден — выбрасывает RuntimeError с инструкцией.
    """
    try:
        from fpdf import FPDF
    except ImportError:
        raise ImportError("Установите fpdf2: pip install fpdf2")

    import os

    # --- Поиск Unicode-шрифта ---
    project_fonts_dir = os.path.join(os.path.dirname(__file__), 'fonts')
    candidate_fonts = [
        # DejaVu в папке проекта (fonts/DejaVuSans.ttf) — кроссплатформенный
        (os.path.join(project_fonts_dir, 'DejaVuSans.ttf'),
         os.path.join(project_fonts_dir, 'DejaVuSans-Bold.ttf')),
        # Windows: Arial (поддерживает кириллицу)
        ('C:/Windows/Fonts/arial.ttf', 'C:/Windows/Fonts/arialbd.ttf'),
        # Linux: DejaVu системный
        ('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf',
         '/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf'),
        # macOS
        ('/Library/Fonts/Arial.ttf', '/Library/Fonts/Arial Bold.ttf'),
    ]

    font_regular = None
    font_bold = None
    for reg, bold in candidate_fonts:
        if os.path.exists(reg):
            font_regular = reg
            font_bold = bold if os.path.exists(bold) else reg
            break

    if font_regular is None:
        raise RuntimeError(
            "Не найден Unicode-шрифт. "
            "Поместите DejaVuSans.ttf в папку fonts/ проекта."
        )

    pdf = FPDF()
    pdf.set_auto_page_break(auto=True, margin=20)
    pdf.add_page()

    pdf.add_font('UniFont', '', font_regular)
    pdf.add_font('UniFont', 'B', font_bold)

    # --- Заголовок ---
    pdf.set_font('UniFont', style='B', size=18)
    pdf.set_text_color(60, 40, 120)  # Фиолетовый акцент
    pdf.multi_cell(0, 12, _clean_text(title), align='C')
    pdf.ln(6)

    # --- Разделитель ---
    pdf.set_draw_color(180, 160, 220)
    pdf.set_line_width(0.5)
    pdf.line(pdf.l_margin, pdf.get_y(), pdf.w - pdf.r_margin, pdf.get_y())
    pdf.ln(8)

    # --- Тело сказки ---
    pdf.set_font('UniFont', size=12)
    pdf.set_text_color(30, 30, 30)

    for para in _paragraphs(body):
        clean_para = _clean_text(para)
        pdf.set_x(pdf.l_margin + 8)  # Отступ первой строки абзаца
        pdf.multi_cell(0, 7, clean_para, align='J')
        pdf.ln(3)

    # --- Подпись ---
    pdf.ln(8)
    pdf.set_draw_color(200, 190, 230)
    pdf.line(pdf.l_margin, pdf.get_y(), pdf.w - pdf.r_margin, pdf.get_y())
    pdf.ln(5)
    pdf.set_font('UniFont', size=9)
    pdf.set_text_color(150, 140, 170)
    pdf.multi_cell(0, 5, _get_app_label(lang), align='C')

    buf = io.BytesIO()
    pdf.output(buf)
    return buf.getvalue()



