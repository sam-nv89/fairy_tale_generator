def generate_epub(title: str, body: str, lang: str = 'ru') -> bytes:
    """
    Генерирует EPUB3-файл — стандарт для большинства e-reader'ов.
    Поддерживается: Kindle (через конвертацию), Kobo, PocketBook, Apple Books.

    Возвращает bytes EPUB-архива для передачи в st.download_button.
    """
    try:
        from ebooklib import epub
    except ImportError:
        raise ImportError("Установите ebooklib: pip install ebooklib")

    book = epub.EpubBook()

    # --- Метаданные ---
    book_id = f"fairytale-{uuid.uuid4().hex[:8]}"
    book.set_identifier(book_id)
    book.set_title(_clean_text(title))
    book.set_language(lang if '-' not in lang else lang.split('-')[0])
    book.add_author('Fairy Tale Generator')
    book.add_metadata('DC', 'description', _get_app_label(lang))
    book.add_metadata('DC', 'date', datetime.date.today().isoformat())

    # --- CSS стиль для красивого отображения ---
    css_content = """
    @charset "UTF-8";
    body {
        font-family: Georgia, 'Times New Roman', serif;
        font-size: 1em;
        line-height: 1.7;
        margin: 1em 1.5em;
        color: #1a1a1a;
        background-color: #fefefe;
    }
    h1 {
        font-size: 1.6em;
        text-align: center;
        color: #3c2878;
        margin-bottom: 1.2em;
        border-bottom: 2px solid #b4a0d8;
        padding-bottom: 0.5em;
    }
    p {
        text-indent: 1.5em;
        margin: 0.5em 0;
        text-align: justify;
    }
    .footer {
        margin-top: 2em;
        font-size: 0.8em;
        color: #888;
        text-align: center;
        border-top: 1px solid #ddd;
        padding-top: 0.8em;
    }
    """
    nav_css = epub.EpubItem(
        uid='style_main',
        file_name='style/main.css',
        media_type='text/css',
        content=css_content.encode('utf-8')
    )
    book.add_item(nav_css)

    # --- Глава со сказкой ---
    html_body = _html_paragraphs(body)
    chapter_html = f"""<?xml version='1.0' encoding='utf-8'?>
<!DOCTYPE html>
<html xmlns="http://www.w3.org/1999/xhtml" xml:lang="{lang}">
<head>
    <meta charset="utf-8"/>
    <title>{_clean_text(title)}</title>
    <link rel="stylesheet" type="text/css" href="style/main.css"/>
</head>
<body>
    <h1>{_clean_text(title)}</h1>
    {html_body}
    <div class="footer">{_get_app_label(lang)}</div>
</body>
</html>"""

    chapter = epub.EpubHtml(
        title=_clean_text(title),
        file_name='story.xhtml',
        lang=lang
    )
    chapter.content = chapter_html.encode('utf-8')
    chapter.add_item(nav_css)
    book.add_item(chapter)

    # --- Навигация ---
    book.toc = [epub.Link('story.xhtml', _clean_text(title), 'story')]
    book.add_item(epub.EpubNcx())
    book.add_item(epub.EpubNav())
    book.spine = ['nav', chapter]

    # --- Запись в буфер ---
    buf = io.BytesIO()
    epub.write_epub(buf, book, {})
    return buf.getvalue()


