def get_export_data(
    fmt: str,
    title: str,
    body: str,
    lang: str = 'ru'
) -> Optional[bytes]:
    """
    Генерирует файл в указанном формате.

    Args:
        fmt:   Ключ формата из EXPORT_FORMATS ('txt', 'pdf', 'epub', 'fb2', 'html')
        title: Заголовок сказки
        body:  Тело сказки
        lang:  Код языка пользователя

    Returns:
        bytes с содержимым файла или None при ошибке
    """
    if fmt not in EXPORT_FORMATS:
        return None
    try:
        return EXPORT_FORMATS[fmt]['generator'](title, body, lang)
    except Exception as e:
        import logging
        logging.getLogger(__name__).error(f"Export error [{fmt}]: {e}")
        return None
