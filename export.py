# TXT
# ---------------------------------------------------------------------------

def generate_txt(title: str, body: str, lang: str = 'ru') -> bytes:
    """
    Генерирует простой текстовый файл (.txt) в кодировке UTF-8.
    Самый универсальный формат — читается на любом устройстве.
    """
    clean_body = _clean_text(body)
    content = f"{title}\n\n{clean_body}\n\n---\n{_get_app_label(lang)}"
    return content.encode('utf-8')


