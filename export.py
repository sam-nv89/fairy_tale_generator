# FB2 (FictionBook 2.0 — XML)
# ---------------------------------------------------------------------------

def generate_fb2(title: str, body: str, lang: str = 'ru') -> bytes:
    """
    Генерирует FictionBook2 (.fb2) — популярный формат в России/СНГ.
    Поддерживается: PocketBook, FBReader, Moon+ Reader, Bookmate.

    FB2 — это XML-файл, строим через ElementTree без внешних зависимостей.
    """
    # Корневой элемент с namespace
    ns = 'http://www.gribuser.ru/xml/fictionbook/2.0'
    xlink_ns = 'http://www.w3.org/1999/xlink'

    ET.register_namespace('', ns)
    ET.register_namespace('xlink', xlink_ns)

    root = ET.Element(f'{{{ns}}}FictionBook')
    root.set(f'xmlns:xlink', xlink_ns)

    # --- Описание книги ---
    description = ET.SubElement(root, f'{{{ns}}}description')
    title_info = ET.SubElement(description, f'{{{ns}}}title-info')

    # Жанр
    genre_el = ET.SubElement(title_info, f'{{{ns}}}genre')
    genre_el.text = 'children'

    # Автор
    author_el = ET.SubElement(title_info, f'{{{ns}}}author')
    first_name = ET.SubElement(author_el, f'{{{ns}}}first-name')
    first_name.text = 'Fairy Tale'
    last_name = ET.SubElement(author_el, f'{{{ns}}}last-name')
    last_name.text = 'Generator'

    # Заголовок
    book_title = ET.SubElement(title_info, f'{{{ns}}}book-title')
    book_title.text = _clean_text(title)

    # Язык
    lang_el = ET.SubElement(title_info, f'{{{ns}}}lang')
    lang_el.text = lang if '-' not in lang else lang.split('-')[0]

    # Дата
    date_el = ET.SubElement(title_info, f'{{{ns}}}date')
    date_el.text = datetime.date.today().isoformat()

    # Аннотация
    annotation = ET.SubElement(title_info, f'{{{ns}}}annotation')
    ann_p = ET.SubElement(annotation, f'{{{ns}}}p')
    ann_p.text = _get_app_label(lang)

    # Документ-инфо
    doc_info = ET.SubElement(description, f'{{{ns}}}document-info')
    doc_author = ET.SubElement(doc_info, f'{{{ns}}}author')
    doc_fn = ET.SubElement(doc_author, f'{{{ns}}}first-name')
    doc_fn.text = 'Fairy Tale Generator'
    doc_id = ET.SubElement(doc_info, f'{{{ns}}}id')
    doc_id.text = uuid.uuid4().hex
    doc_version = ET.SubElement(doc_info, f'{{{ns}}}version')
    doc_version.text = '1.0'
    doc_date = ET.SubElement(doc_info, f'{{{ns}}}date')
    doc_date.text = datetime.date.today().isoformat()

    # --- Тело книги ---
    fb2_body = ET.SubElement(root, f'{{{ns}}}body')
    section = ET.SubElement(fb2_body, f'{{{ns}}}section')

    # Заголовок секции
    sec_title = ET.SubElement(section, f'{{{ns}}}title')
    sec_title_p = ET.SubElement(sec_title, f'{{{ns}}}p')
    sec_title_p.text = _clean_text(title)

    # Абзацы
    for para in _paragraphs(body):
        p_el = ET.SubElement(section, f'{{{ns}}}p')
        p_el.text = _clean_text(para)

    # Подпись
    empty_p = ET.SubElement(section, f'{{{ns}}}empty-line')
    footer_p = ET.SubElement(section, f'{{{ns}}}p')
    footer_p.text = f"— {_get_app_label(lang)}"

    # --- Сериализация в bytes ---
    # Используем short_empty_elements=False для полной совместимости с FB2-ридерами
    tree = ET.ElementTree(root)
    buf = io.BytesIO()
    tree.write(buf, encoding='utf-8', xml_declaration=True)
    return buf.getvalue()


