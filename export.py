# HTML (автономный файл)
# ---------------------------------------------------------------------------

def generate_html(title: str, body: str, lang: str = 'ru') -> bytes:
    """
    Генерирует красивый автономный HTML-файл.
    Читается в любом браузере, поддерживает все языки.
    Хорошо выглядит на телефоне и планшете (responsive).
    """
    clean_title = _clean_text(title)
    html_body = _html_paragraphs(body)
    today = datetime.date.today().strftime('%d.%m.%Y')

    html = f"""<!DOCTYPE html>
<html lang="{lang}">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>{clean_title}</title>
    <style>
        * {{ box-sizing: border-box; margin: 0; padding: 0; }}
        body {{
            font-family: Georgia, 'Times New Roman', serif;
            font-size: 18px;
            line-height: 1.8;
            color: #1a1a2e;
            background: linear-gradient(135deg, #f5f3ff 0%, #ede9fe 100%);
            min-height: 100vh;
            padding: 2rem 1rem;
        }}
        .container {{
            max-width: 720px;
            margin: 0 auto;
            background: #ffffff;
            border-radius: 16px;
            box-shadow: 0 8px 40px rgba(102, 78, 234, 0.12);
            padding: 3rem 3.5rem;
        }}
        h1 {{
            font-size: 2em;
            color: #3c2878;
            text-align: center;
            margin-bottom: 0.5rem;
            line-height: 1.3;
        }}
        .divider {{
            border: none;
            border-top: 2px solid #b4a0d8;
            margin: 1.5rem 0 2rem;
        }}
        p {{
            text-indent: 1.8em;
            margin-bottom: 0.9em;
            text-align: justify;
        }}
        .footer {{
            margin-top: 2.5rem;
            padding-top: 1rem;
            border-top: 1px solid #e0d9f5;
            font-size: 0.8em;
            color: #9c8ec0;
            text-align: center;
        }}
        @media (max-width: 600px) {{
            .container {{ padding: 2rem 1.5rem; }}
            h1 {{ font-size: 1.5em; }}
            body {{ font-size: 16px; }}
        }}
    </style>
</head>
<body>
    <div class="container">
        <h1>{clean_title}</h1>
        <hr class="divider">
        {html_body}
        <div class="footer">
            {_get_app_label(lang)} &bull; {today}
        </div>
    </div>
</body>
</html>"""
    return html.encode('utf-8')


